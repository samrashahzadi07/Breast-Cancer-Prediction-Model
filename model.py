# ---------------------------------------------------------------
# STEP 1: Importing the Dependencies
# ---------------------------------------------------------------
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import sklearn.datasets
from sklearn.model_selection import train_test_split

"""## Step 2: Loading the Data
We use the built-in Breast Cancer dataset from sklearn.
"""

# loading the data from sklearn
breast_cancer_dataset = sklearn.datasets.load_breast_cancer()
print(breast_cancer_dataset)

"""## Step 3: Data Collection & Processing
Convert the dataset into a Pandas DataFrame for easier manipulation.
Add the target column (`label`) where:
- 0 = Malignant
- 1 = Benign
"""

# loading the data to a data frame
data_frame = pd.DataFrame(breast_cancer_dataset.data, columns=breast_cancer_dataset.feature_names)

# print the first 5 rows of the dataframe
data_frame.head()

# adding the 'target' column to the data frame
data_frame['label'] = breast_cancer_dataset.target

# print last 5 rows of the dataframe
data_frame.tail()

# number of rows and columns in the dataset
data_frame.shape

# getting some information about the data
data_frame.info()

# checking for missing values
data_frame.isnull().sum()

# statistical measures about the data
data_frame.describe()

# checking the distribution of Target Variable
data_frame['label'].value_counts()

"""## Step 4: Separating the Features and Target
We split the dataset into:
- Features (X): all columns except `label`
- Target (Y): the `label` column
"""

data_frame.groupby('label').mean()

X = data_frame.drop(columns='label', axis=1)
Y = data_frame['label']

print(X)
print(Y)

"""## Step 5: Splitting into Training and Testing Sets
We use an 80/20 split with `random_state=2` for reproducibility.
"""

X_train, X_test, Y_train, Y_test = train_test_split(X, Y, test_size=0.2, random_state=2)
print(X.shape, X_train.shape, X_test.shape)

"""## Step 6: Standardizing the Data
Scaling ensures all features contribute equally to the training process.
"""

from sklearn.preprocessing import StandardScaler

scaler = StandardScaler()
X_train_std = scaler.fit_transform(X_train)
X_test_std = scaler.transform(X_test)

"""## Step 7: Building the Neural Network
We create a simple feedforward neural network:
- Flatten layer → reshapes input
- Dense layer (20 neurons, ReLU activation)
- Dense layer (2 neurons, Sigmoid activation)
"""

import tensorflow as tf
tf.random.set_seed(3)
from tensorflow import keras

# setting up the layers of Neural Network
model = keras.Sequential([
    keras.layers.Flatten(input_shape=(30,)),
    keras.layers.Dense(20, activation='relu'),
    keras.layers.Dense(2, activation='sigmoid')
])

# compiling the Neural Network
model.compile(optimizer='adam',
              loss='sparse_categorical_crossentropy',
              metrics=['accuracy'])

# training the Neural Network
history = model.fit(X_train_std, Y_train, validation_split=0.1, epochs=10)

"""## Step 8: Visualizing Accuracy and Loss
We plot accuracy and loss for both training and validation sets to check model performance.
"""

plt.plot(history.history['accuracy'])
plt.plot(history.history['val_accuracy'])
plt.title('Model Accuracy')
plt.ylabel('Accuracy')
plt.xlabel('Epoch')
plt.legend(['Training', 'Validation'], loc='lower right')

plt.plot(history.history['loss'])
plt.plot(history.history['val_loss'])
plt.title('Model Loss')
plt.ylabel('Loss')
plt.xlabel('Epoch')
plt.legend(['Training', 'Validation'], loc='upper right')

"""## Step 9: Accuracy on Test Data
We evaluate the model on unseen test data and check predictions.
"""

loss, accuracy = model.evaluate(X_test_std, Y_test)
print("Test Accuracy:", accuracy)

print(X_test_std.shape)
print(X_test_std[0])

Y_pred = model.predict(X_test_std)
print("Prediction shape:", Y_pred.shape)
print("First Prediction:", Y_pred[0])

# Example: argmax function for converting probabilities into labels
my_list = [0.25, 0.56]
index_of_max_value = np.argmax(my_list)
print(my_list)
print("Index of max value:", index_of_max_value)

# Converting probability predictions to class labels
Y_pred_labels = [np.argmax(i) for i in Y_pred]
print(Y_pred_labels)

"""## Step 10: Building a Predictive System
We test the model with custom input data.
"""

input_data = (11.76,21.6,74.72,427.9,0.08637,0.04966,0.01657,0.01115,0.1495,0.05888,
              0.4062,1.21,2.635,28.47,0.005857,0.009758,0.01168,0.007445,0.02406,
              0.001769,12.98,25.72,82.98,516.5,0.1085,0.08615,0.05523,0.03715,
              0.2433,0.06563)

# change the input_data to a numpy array
input_data_as_numpy_array = np.asarray(input_data)

# reshape the numpy array as we are predicting for one data point
input_data_reshaped = input_data_as_numpy_array.reshape(1, -1)

# standardizing the input data
input_data_std = scaler.transform(input_data_reshaped)

prediction = model.predict(input_data_std)
print(prediction)

prediction_label = [np.argmax(prediction)]
print("Predicted label:", prediction_label)

if prediction_label[0] == 0:
    print('The tumor is Malignant')
else:
    print('The tumor is Benign')

